// Helper to generate realistic daily statistics snapshots
export const generateSnapshotsForListing = (listingId: string, baseCount: number, days = 30): StatisticsSnapshot[] => {
  const snapshots: StatisticsSnapshot[] = [];
  const now = new Date('2026-10-18T10:00:00Z');
  
  let current = baseCount - Math.floor(baseCount * 0.08); // started ~8% lower 30 days ago
  
  for (let i = days; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    // Growth with slight variation
    const dayGrowth = Math.floor((Math.random() * 0.008 + 0.001) * current) + 12;
    current += dayGrowth;
    
    const views = Math.floor(current * 0.33);
    const eng = +(30 + Math.random() * 6).toFixed(1);

    snapshots.push({
      id: `snap-${listingId}-${dateStr}`,
      listingId,
      snapshotDate: dateStr,
      audienceCount: current,
      viewsPerPost: views,
      engagementRate: eng,
      absoluteChange24h: dayGrowth,
      percentChange24h: +((dayGrowth / (current - dayGrowth)) * 100).toFixed(2),
      dataSource: 'api_sync',
      isVerified: true,
    });
  }
  return snapshots;
};
